#!/usr/bin/env python3
"""
MD5 Collision Lab - "Software Certification Authority"

Small HTTP service that receives the files produced by the student, verifies them
and, ONLY IF the verification succeeds, returns the per-sandbox flag of the level.

  POST /submit/<task>/<filename>   raw body = file content (max 4 MB)
  GET  /verify/<task>[?k=v&...]    verify the uploaded files / quiz answers
  GET  /status                     list uploaded files
  GET  /                           help

Flags, token and prefix are read from /opt/authority (root only, mode 0700), so the
student can never read them. Student binaries are executed in a throw-away sandbox:
unprivileged uid, no network, CPU/file/process limits, short timeout.
"""
import hashlib
import json
import os
import re
import resource
import shutil
import subprocess
import tempfile
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import urlparse, parse_qs

BASE = "/opt/authority"
UPLOADS = "/var/lib/authority/uploads"
MAX_UPLOAD = 4 * 1024 * 1024
LISTEN = ("0.0.0.0", int(os.environ.get("AUTHORITY_PORT", "8080")))

with open(os.path.join(BASE, "config.json")) as fh:
    CFG = json.load(fh)
TOKEN = CFG["token"]
FLAGS = CFG["flags"]
with open(os.path.join(BASE, "prefix.bin"), "rb") as fh:
    PREFIX = fh.read()

NAME_RE = re.compile(r"^[A-Za-z0-9_.-]{1,40}$")
TASKS = {
    "t1": ["out1.bin", "out2.bin"],
    "t1q": [],
    "t2": ["mt.bin", "nt.bin"],
    "t3a": ["a.out"],
    "t3b": ["v1.out", "v2.out"],
    "t4": ["benign.out", "malicious.out"],
}
LOCK = threading.Lock()


# ----------------------------------------------------------------- helpers
def md5(b):
    return hashlib.md5(b).hexdigest()


def load(task, name):
    p = os.path.join(UPLOADS, task, name)
    if os.path.isfile(p):
        with open(p, "rb") as fh:
            return fh.read()
    return None


def diff_offsets(a, b):
    return [i for i in range(min(len(a), len(b))) if a[i] != b[i]]


def parse_int(s):
    s = (s or "").strip()
    try:
        return int(s, 16) if s.lower().startswith("0x") else int(s)
    except ValueError:
        return None


def run_sandboxed(data):
    """Run an untrusted ELF as 'nobody', without network, with limits."""
    d = tempfile.mkdtemp(prefix="run_", dir="/tmp")
    try:
        os.chmod(d, 0o755)
        prog = os.path.join(d, "prog")
        with open(prog, "wb") as fh:
            fh.write(data)
        os.chmod(prog, 0o755)

        def limits():
            resource.setrlimit(resource.RLIMIT_CPU, (5, 5))
            resource.setrlimit(resource.RLIMIT_FSIZE, (1 << 20, 1 << 20))
            resource.setrlimit(resource.RLIMIT_NPROC, (64, 64))
            os.setsid()

        cmd = ["unshare", "--net", "setpriv", "--reuid=65534", "--regid=65534",
               "--clear-groups", "--no-new-privs", prog]
        try:
            r = subprocess.run(cmd, capture_output=True, timeout=8, cwd=d,
                               preexec_fn=limits, env={"PATH": "/usr/bin:/bin"})
        except subprocess.TimeoutExpired:
            return None, "timeout"
        except Exception as exc:  # pragma: no cover
            return None, "cannot execute: %s" % exc
        return r.stdout[:200000].decode("latin-1"), r.returncode
    finally:
        shutil.rmtree(d, ignore_errors=True)


def is_elf(b):
    return b is not None and b[:4] == b"\x7fELF"


def need(task, names):
    files = [load(task, n) for n in names]
    missing = [n for n, f in zip(names, files) if f is None]
    return files, missing


# ----------------------------------------------------------------- checks
# Every check returns (ok, message, extra)
def check_t1():
    (a, b), missing = need("t1", TASKS["t1"])
    if missing:
        return False, "Missing upload(s) for t1: %s. Use: authority-upload t1 out1.bin out2.bin" % ", ".join(missing), None
    L = len(PREFIX)
    padded = ((L + 63) // 64) * 64
    if len(a) != len(b):
        return False, "out1.bin and out2.bin do not have the same size.", None
    if len(a) != padded + 128:
        return False, ("Unexpected size (%d bytes). Were the files generated by md5collgen from YOUR "
                       "~/lab/task1/prefix.txt?" % len(a)), None
    if a[:L] != PREFIX or b[:L] != PREFIX:
        return False, "The files do not start with the content of YOUR prefix.txt (it is different for every student).", None
    if a == b:
        return False, "The two files are identical: a collision needs two DIFFERENT files.", None
    if md5(a) != md5(b):
        return False, "The two files do not have the same MD5 hash.", None
    return True, "", (a, b)


def check_t1q(params):
    ok, msg, data = check_t1()
    if not ok:
        return False, "Task 1 files must be valid first. " + msg, None
    a, b = data
    L = len(PREFIX)
    padded = ((L + 63) // 64) * 64
    q1 = parse_int(params.get("q1", [""])[0])
    q2 = parse_int(params.get("q2", [""])[0])
    raw3 = params.get("q3", [""])[0]
    try:
        q3 = sorted(int(x, 16) if x.lower().startswith("0x") else int(x)
                    for x in re.split(r"[,\s;]+", raw3.strip()) if x)
    except ValueError:
        q3 = None
    wrong = []
    if q1 != padded - L:
        wrong.append("Q1")
    if q2 != 192:
        wrong.append("Q2")
    if q3 != diff_offsets(a, b):
        wrong.append("Q3")
    if wrong:
        return False, "Wrong answer(s): %s" % ", ".join(wrong), None
    return True, "All three answers are correct.", None


def check_t2():
    ok, msg, data = check_t1()
    if not ok:
        return False, "Task 1 files must be valid first. " + msg, None
    a, b = data
    (m, n), missing = need("t2", TASKS["t2"])
    if missing:
        return False, "Missing upload(s) for t2: %s. Use: authority-upload t2 mt.bin nt.bin" % ", ".join(missing), None
    if not m.startswith(a) or not n.startswith(b):
        return False, "mt.bin must be out1.bin || T and nt.bin must be out2.bin || T.", None
    tm, tn = m[len(a):], n[len(b):]
    if tm != tn:
        return False, "The suffix T appended to both files must be the SAME.", None
    if len(tm) == 0:
        return False, "The suffix T is empty.", None
    if TOKEN.encode() not in tm:
        return False, "T must contain your personal token (use ~/lab/task2/suffix.txt).", None
    if m == n:
        return False, "mt.bin and nt.bin are identical.", None
    if md5(m) != md5(n):
        return False, "MD5(M||T) != MD5(N||T).", None
    return True, "MD5(M||T) == MD5(N||T) with M != N: the property holds.", None


def array_offset(ref):
    if not is_elf(ref):
        return None
    if ref.count(b"A" * 200) != 1:
        return None
    return ref.find(b"A" * 200)


def check_t3a(params):
    (a,), missing = need("t3a", TASKS["t3a"])
    if missing:
        return False, "Upload your binary first: authority-upload t3a a.out", None
    if not is_elf(a):
        return False, "a.out is not an ELF executable.", None
    off = array_offset(a)
    if off is None:
        return False, ("Could not find exactly one array of 200 x 0x41 ('A') in a.out. "
                       "Compile ~/lab/task3/task3.c without modifying the array."), None
    out, rc = run_sandboxed(a)
    if out != "[%s] %s\n" % (TOKEN, "41" * 200):
        return False, "Running a.out does not give the expected output. Compile YOUR ~/lab/task3/task3.c.", None
    given = parse_int(params.get("offset", [""])[0])
    if given is None:
        return False, "Give the offset: authority-verify t3a offset=<n> (0-based, decimal or 0x hex).", None
    if given != off:
        return False, "Wrong offset for the start of the array.", None
    return True, "Array located correctly.", None


def check_t3b():
    ref = load("t3a", "a.out")
    off = array_offset(ref)
    if off is None:
        return False, "Complete level 'Find the array' first (t3a): authority-upload t3a a.out", None
    (v1, v2), missing = need("t3b", TASKS["t3b"])
    if missing:
        return False, "Missing upload(s) for t3b: %s. Use: authority-upload t3b v1.out v2.out" % ", ".join(missing), None
    if not (is_elf(v1) and is_elf(v2)):
        return False, "Both files must be ELF executables.", None
    if len(v1) != len(ref) or len(v2) != len(ref):
        return False, "The executables must have the same size as a.out.", None
    if v1 == v2:
        return False, "The two executables are identical.", None
    if md5(v1) != md5(v2):
        return False, "The two executables do not have the same MD5 hash.", None
    for name, v in (("v1.out", v1), ("v2.out", v2)):
        d = diff_offsets(ref, v)
        if any(not (off <= x < off + 200) for x in d):
            return False, "%s differs from a.out outside the xyz array." % name, None
    d12 = diff_offsets(v1, v2)
    if max(d12) - min(d12) >= 128:
        return False, "The two files must differ only inside one 128-byte block.", None
    o1, r1 = run_sandboxed(v1)
    o2, r2 = run_sandboxed(v2)
    if o1 is None or o2 is None or r1 != 0 or r2 != 0:
        return False, "One of the executables does not run correctly (did you chmod +x? is the file corrupted?).", None
    pre = "[%s] " % TOKEN
    if not (o1.startswith(pre) and o2.startswith(pre)):
        return False, "Unexpected program output.", None
    if o1 == o2:
        return False, "Both programs print the same array: they must print different contents.", None
    return True, "Same MD5, different output.", None


def check_t4():
    (b, m), missing = need("t4", TASKS["t4"])
    if missing:
        return False, "Missing upload(s) for t4: %s. Use: authority-upload t4 benign.out malicious.out" % ", ".join(missing), None
    if not (is_elf(b) and is_elf(m)):
        return False, "Both files must be ELF executables.", None
    if len(b) != len(m) or b == m:
        return False, "The two programs must have the same size and must be different.", None
    if md5(b) != md5(m):
        return False, "The two programs do not have the same MD5 hash (the certificate would not match).", None
    d = diff_offsets(b, m)
    if max(d) - min(d) >= 128:
        return False, "The two programs must differ only inside one 128-byte block.", None
    ob, rb = run_sandboxed(b)
    om, rm = run_sandboxed(m)
    if ob != "BENIGN:%s\n" % TOKEN:
        return False, "benign.out does not behave as the benign version (expected: X and Y contents equal).", None
    if om != "MALICIOUS:%s\n" % TOKEN:
        return False, "malicious.out does not behave as the malicious version (expected: X and Y contents different).", None
    return True, ("The authority certified the benign program, and the certificate (MD5 %s) is also "
                  "valid for the malicious one!" % md5(b)), None


def verify(task, params):
    if task == "t1":
        ok, msg, _ = check_t1()
        if ok:
            msg = "Valid MD5 collision generated from your prefix. md5 = %s" % md5(load("t1", "out1.bin"))
    elif task == "t1q":
        ok, msg, _ = check_t1q(params)
    elif task == "t2":
        ok, msg, _ = check_t2()
    elif task == "t3a":
        ok, msg, _ = check_t3a(params)
    elif task == "t3b":
        ok, msg, _ = check_t3b()
    elif task == "t4":
        ok, msg, _ = check_t4()
    else:
        return "Unknown task '%s'. Valid tasks: %s\n" % (task, ", ".join(TASKS))
    if ok:
        return "SUCCESS - %s\nFLAG: %s\n" % (msg, FLAGS[task])
    return "FAILED - %s\n" % msg


HELP = """MD5 Collision Lab - Certification Authority
  authority-upload <task> <file>...     upload files
  authority-verify <task> [key=value]   verify and get the flag
Tasks: t1 (out1.bin out2.bin) | t1q (q1= q2= q3=) | t2 (mt.bin nt.bin) |
       t3a (a.out, offset=) | t3b (v1.out v2.out) | t4 (benign.out malicious.out)
"""


class Handler(BaseHTTPRequestHandler):
    server_version = "CertAuthority/1.0"

    def log_message(self, fmt, *args):  # keep journal small
        pass

    def _send(self, code, text):
        body = text.encode()
        self.send_response(code)
        self.send_header("Content-Type", "text/plain; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_POST(self):
        m = re.match(r"^/submit/(\w+)/([^/?]+)$", urlparse(self.path).path)
        if not m or m.group(1) not in TASKS or not NAME_RE.match(m.group(2)):
            return self._send(400, "Bad request. Valid tasks: %s\n" % ", ".join(TASKS))
        task, name = m.groups()
        try:
            length = int(self.headers.get("Content-Length", "-1"))
        except ValueError:
            length = -1
        if length < 0 or length > MAX_UPLOAD:
            return self._send(413, "File too large (max 4 MB) or no Content-Length.\n")
        data = self.rfile.read(length)
        with LOCK:
            d = os.path.join(UPLOADS, task)
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, name), "wb") as fh:
                fh.write(data)
        return self._send(200, "OK %s (%d bytes, md5 %s)\n" % (name, len(data), md5(data)))

    def do_GET(self):
        u = urlparse(self.path)
        if u.path == "/":
            return self._send(200, HELP)
        if u.path == "/status":
            lines = []
            for t in TASKS:
                d = os.path.join(UPLOADS, t)
                if os.path.isdir(d):
                    for f in sorted(os.listdir(d)):
                        lines.append("%s/%s  %d bytes" % (t, f, os.path.getsize(os.path.join(d, f))))
            return self._send(200, "\n".join(lines) + "\n" if lines else "nothing uploaded yet\n")
        m = re.match(r"^/verify/(\w+)$", u.path)
        if not m:
            return self._send(404, "Not found\n")
        with LOCK:
            try:
                res = verify(m.group(1), parse_qs(u.query))
            except Exception as exc:  # never crash the service
                res = "FAILED - internal error while verifying (%s)\n" % type(exc).__name__
        return self._send(200, res)


if __name__ == "__main__":
    os.makedirs(UPLOADS, exist_ok=True)
    ThreadingHTTPServer(LISTEN, Handler).serve_forever()
